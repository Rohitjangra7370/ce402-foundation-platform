// Extracts every "SRC:" comment from src/engine.js into docs/sources.md and docs/sources.json (traceability appendix of the report).
// Each /* ... */ block is taken on its own and attached to the function/const that follows it directly.
const fs = require('fs');
const text = fs.readFileSync(__dirname + '/../src/engine.js', 'utf8');
const rows = [];
const re = /\/\*((?:(?!\*\/)[\s\S])*)\*\//g;
let m;
while ((m = re.exec(text))) {
  const body = m[1]; if (body.indexOf('SRC:') < 0) continue;
  const after = text.slice(m.index + m[0].length, m.index + m[0].length + 200);
  const f = /^\s*(?:function\s+([A-Za-z0-9_]+)|const\s+([A-Za-z0-9_]+))/.exec(after);
  if (!f) continue;                                    // e.g. the file header: not attached to a function
  const clean = s => s.split('\n').map(l => l.trim()).filter(Boolean).join(' ').replace(/\s+/g, ' ');
  const i = body.indexOf('SRC:');
  const what = clean(body.slice(0, i)).replace(/^=+\s*/, '') || '(see source)';
  rows.push({ fn: f[1] || f[2], what, src: clean(body.slice(i + 4)) });
}
fs.writeFileSync(__dirname + '/../docs/sources.json', JSON.stringify(rows, null, 1));
fs.writeFileSync(__dirname + '/../docs/sources.md', '# Sources of every equation in src/engine.js\n\n(generated by tools/sources.js from the SRC: comments)\n\n| function | what it does | source |\n|---|---|---|\n' + rows.map(r => `| \`${r.fn}\` | ${r.what.slice(0, 200)} | ${r.src} |`).join('\n') + '\n');
console.log(rows.length + ' sourced functions: ' + rows.map(r => r.fn).join(', '));
// exported functions without an SRC comment (helpers with no equation of their own are expected here)
const tail = text.slice(text.lastIndexOf('return {'));
const exported = tail.replace(/^return \{/, '').split('};')[0].split(/[,\s]+/).filter(n => /^[A-Za-z_][A-Za-z0-9_]*$/.test(n));
const have = new Set(rows.map(r => r.fn));
console.log('exported without SRC (expected: constants and helpers only):', exported.filter(n => !have.has(n)).join(', ') || '(none)');
