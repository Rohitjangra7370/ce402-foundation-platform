// Generates src/examples.js from data/site.json so the example boreholes are never typed twice.
// The calculation engine and the UI never import this file; the UI only offers it as an optional button.
const fs = require('fs');
const S = require('../data/site.json');
const ex = {};
for (const [k, d] of Object.entries(S.boreholes)) {
  ex[k] = { gl: d.gl, wtMeasured: d.wtMeasured, wtHigh: d.wtHigh, wtLow: d.wtLow,
    layers: d.layers.map(L => { const o = Object.assign({}, L); delete o.sym; delete o.src; return o; }) };
}
ex.lab = S.lab;
fs.writeFileSync(__dirname + '/../src/examples.js',
  '/* EXAMPLE DATA ONLY - generated by tools/make_examples.js from data/site.json.\n   Loaded into the input forms when the user presses a "Load BH-x" button; never used by engine.js. */\nwindow.EXAMPLES = ' + JSON.stringify(ex, null, 1) + ';\n');
console.log('wrote src/examples.js');
